/**
 * @brief Инициализация конечного автомата сварки
 */
void FSM_MMA_Init(void);

/**
 * @brief Высокоскоростной диспетчер переключения состояний
 * @note Вызывается строго внутри прерывания TIM2 (20 кГц) сразу после фильтрации АЦП.
 * @param voltage Отфильтрованное физическое напряжение на дуге (Вольты)
 * @param current Отфильтрованный физический ток в силовой цепи (Амперы)
 */
void FSM_MMA_Process(uint16_t voltage, uint16_t current);

/**
 * @brief Принудительный перевод автомата в состояние критической аварии
 * @note Вызывается мгновенно из прерываний аварийных GPIO (EXTI) или защитных потоков.
 */
void FSM_MMA_Force_Fault(void);

/**
 * @brief Безопасное чтение текущего состояния автомата (для UI и индикации)
 * @note Сама внутренняя переменная состояния объявлена как volatile в ОЗУ, 
 *       что гарантирует чтение актуальных данных фоновым потоком UI (while(1)).
 * @return Текущее активное состояние (тип mma_state_t)
 */
mma_state_t FSM_MMA_Get_State(void);

/**
 * @brief Обновление пользовательской базовой уставки тока (изменяется энкодером)
 * @param new_current_setpoint Желаемый ток сварки в Амперах (например, от 20.0f до 160.0f)
 */
void FSM_MMA_Set_User_Current(uint16_t new_current_setpoint);

