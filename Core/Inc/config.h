#define ADC_CHANNELS            6U   /**< Активных каналов регулярной группы (соответствует
                                           SequencerLength = 6 RANKS в MX_ADC1_Init):
                                           PA0/IN0, PA1/IN1, PA2/IN2, PA3/IN3, PA5/IN5, PB0/IN8.
                                           PA5 освобожден под АЦП переносом TIM2_CH1 на PA15,
                                           PB0 подключен как ADC12_IN8 (см. Docs/pin_map.md) */
#define ADC_OVERSAMPLING        16U  /**< Глубина программного окна оверсэмплинга (выборок на канал) */

/**
 * @brief Общий размер одного окна данных регулярной группы.
 * Расчет выполняется предкомпилятором: 6 каналов * 16 выборок = 96 ячеек.
 */
#define ADC_BUFFER_SIZE         (ADC_CHANNELS * ADC_OVERSAMPLING)

/**
 * @brief Общий физический размер буфера DMA для реализации Ping-Pong буферизации.
 * Равен удвоенному размеру базового окна: 96 * 2 = 192 элементов uint16_t.
 */
#define PING_PONG_BUFF_SIZE     (ADC_BUFFER_SIZE * 2U)

/**
 * @brief Перечисление строго зафиксированных индексов каналов в буфере DMA.
 * Соответствует физическому порядку сканирования Rank 1 ... Rank 6 в настройках АЦП.
 */
typedef enum {
    ADC_CURRENT_IDX   = 0U,          /**< Ток дуги сварки (PA0/IN0), Rank 1 */
    ADC_VOLTAGE_IDX   = 1U,          /**< Напряжение на дуге (PA1/IN1), Rank 2 */
    ADC_V15V_IDX      = 2U,          /**< Шина +15В питания затворов драйверов (PA2/IN2), Rank 3 */
    ADC_TEMP_IDX      = 3U,          /**< Термистор силового моста IGBT (PA3/IN3), Rank 4 */
    ADC_TEMP_DIO_IDX  = 4U,          /**< Термистор выходных диодов (PA5/IN5), Rank 5 */
    ADC_FAN_CURR_IDX  = 5U           /**< Ток потребления вентилятора (PB0/IN8), Rank 6 */
} Adc_Channel_Index_t;

