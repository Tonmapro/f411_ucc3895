/* Формула перевода: Код = (Физическое_Напряжение_в_Вольтах / ADC_VOLTAGE_COEFF) */

#define ADC_THRES_NO_LOAD       2459U /**< ~60В ХХ (Порог фиксации обрыва дуги/Холостого хода) */
#define ADC_THRES_ARC_FORCE     778U  /**< ~19В (Порог короткой дуги, требующий Форсажа) */
#define ADC_THRES_ANTI_STICK    410U  /**< ~10В (Порог жесткого КЗ при залипании электрода) */

/* Порог фиксации касания электродом в режиме ОCV: напряжение упало с уровня ХХ
   минимум вдвое (ОCV/2 ~ 30В) при протекающем дежурном токе -> дуга зажигается */
#define ADC_THRES_ARC_STRIKE    (ADC_THRES_NO_LOAD / 2U) /**< ~30В: касание при наличии ОCV */

/* Порог фиксации обрыва дуги: напряжение вернулось к уровню ХХ (>=40В) при токе,
   упавшем практически до нуля (<100 кодов ~ 5А). Пара условий отсекает ложные
   срабатывания при растяжке дуги (V растет, но ток еще течет) и не зависит
   от точного значения ОCV конкретного железа */
#define ADC_THRES_ARC_BREAK     1638U /**< ~40В: уровень ХХ при обрыве дуги (ток ~0) */

/* Lift-TIG: порог "дуга зажглась" при отрыве вольфрама от детали.
   КЗ вольфрама дает ~1-3В, дуга Lift 9-16В, ОCV ~60В: порог между КЗ и дугой */
#define ADC_THRES_TIG_ARC       307U  /**< ~7.5В: дуга зажглась при отрыве (Lift-старт) */

/* Порог аварии «пропало питание драйверов» (канал +15В, PA2, RANK3).
   Было «<200 кодов» (0.16 В на пине ≈ 0.9 В на шине) — различало только полный ноль,
   и висящий/неподключённый измерительный вход (оседает на 0.2-0.5 В) то попадал,
   то не попадал в аварию → «плавающее» поведение на макете.
   Стало 700 кодов = 0.545 В на пине ≈ 3.1 В на шине:
   - реальная шина 12-15 В (делитель 47к/10к) даёт 2400-3400 кодов — запас 3-5×;
   - потеря шины (<3 В) и висящий вход → детерминированная «220V-!»;
   - при этом нет ложных срабатываний от кратковременных просадок рабочей шины. */
#define ADC_THRES_LOW_15V       700U

#define TIG_UPSLOPE_MS          300U  /**< Плавный подъем тока до уставки после зажигания дуги */
#define TIG_STICK_TIMEOUT_MS    2000U /**< Таймаут «вольфрам прилип к детали» в TIG_LIFT: возврат на ХХ */

#define FSM_STARTUP_GRACE_MS    200U  /**< Пауза аппаратных проверок после сброса: EMA-фильтры
                                            АЦП стартуют с 0 и сходятся ~40-80 мс; без паузы
                                            первый тик FSM видит код 0 (обрыв 15В!) и защёлкивает
                                            ложный FAULT. Аналогично для барьера перегрева и
                                            open-проверки кулера в cooling.c */

#define FW_BUILD                16U   /**< V16: ровные оптические интервалы крупного
                                            шрифта (зазор по «чернилам» глифов) и
                                            'A' 16x32 в одну высоту с цифрами.
                                            V15: единый шрифт аварий, ток 24x32.
                                            V14: исправлены шрифт аварий и строка диагностики.
                                            V13: PA3/PA5/PB0 остаются ANALOG/no pull,
                                            как настроено в MX_ADC1_Init.
                                            INPUT+PULL_UP из V5 отменён после A/B-теста PA3.
                                            Обрыв NTC требует внешней подтяжки.
                                            Порог LOW_15V=700 не гарантирует детекцию
                                            плавающего входа. */



