#ifndef INC_ENCODER_H_
#define INC_ENCODER_H_

#include <stdint.h>
#include "main.h"

/* ========================================================================== */
/*               ПОМЕХОУСТОЙЧИВЫЕ НАСТРОЙКИ ФИЛЬТРАЦИИ                        */
/* ========================================================================== */

/**
 * @brief Размер окна мажоритарного (медианного) фильтра.
 * @note  Нечетное число "5" позволяет процессору полностью вырезать до 
 *        2-х подряд идущих импульсных всплесков ЭМП от зажигания дуги.
 */
#define ENCODER_WINDOW_SIZE    5U  

/* ========================================================================== */
/*                         ГЛОБАЛЬНЫЕ ПЕРЕМЕННЫЕ ИНТЕРФЕЙСА                   */
/* ========================================================================== */

/**
 * @brief  Флаг текущего фокуса ввода пользователя.
 * @note   0 — вращение ручки изменяет Ток, 1 — изменяет Вольты ограничения ХХ.
 *         Экспортируется для ui_manager.c [pdf_K8I6_K.pdf].
 */
extern uint8_t ui_edit_target; 

/* ========================================================================== */
/*                          СИСТЕМНЫЕ ПРОТОТИПЫ ФУНКЦИЙ                       */
/* ========================================================================== */

/**
 * @brief  Аппаратная низкоуровневая инициализация энкодера.
 *         Сбрасывает буферы истории и запускает счетчик таймера TIM5 через регистры LL.
 */
void Encoder_Init(void);

/**
 * @brief  Высокоскоростной асинхронный опрос и фильтрация шагов энкодера.
 * @note   Должен вызываться непрерывно в главном суперцикле while(1).
 *         Функция аппаратно считывает TIM5, прогоняет шаги через медианный фильтр,
 *         проверяет удержание кнопки с защитой от дребезга и атомарно обновляет 
 *         переменную Inverter.target_current [pdf_G_X6G-.pdf, pdf_mC_QGf.pdf].
 */
void Encoder_Update_Value(void);

/**
 * @brief  Прямое чтение текущего отфильтрованного значения пользовательской уставки.
 * @retval Отфильтрованный базовый ток в физических Амперах.
 */
uint16_t Encoder_Get_Value(void);

/**
 * @brief  Атомарная проверка фиксации осознанного клика по кнопке.
 * @note   Автоматически сбрасывает внутренний флаг события при вызове (принцип очереди).
 *         Вызывается диспетчером интерфейса в ui_manager.c.
 * @retval 1 — клик зафиксирован, 0 — нажатия не было.
 */
uint8_t Encoder_Is_Pressed(void);

/**
 * @brief Принудительная установка уставки тока (синхронизация после Config_Load).
 * @param current Загруженная из Flash уставка в Амперах (ограничивается барьерами).
 * @note  Заполняет весь медианный буфер одним значением — фильтр мгновенно
 *        принимает уставку без переходного процесса от дефолта.
 */
void Encoder_Set_Value(uint16_t current);

#endif /* INC_ENCODER_H_ */
