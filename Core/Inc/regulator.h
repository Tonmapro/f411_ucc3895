#ifndef REGULATOR_H
#define REGULATOR_H

#include "main.h"

/**
 * @brief Структура конфигурации и внутренних переменных ПИ-регулятора тока.
 * @note  Экспортируется для возможности диагностики параметров через ui_manager.c.
 */
typedef struct {
    float Kp;             // Пропорциональный коэффициент (Вольт / Ампер)
    float Ki;             // Интегральный коэффициент (уже предрассчитанный: Ki_raw * dt, Вольт / Ампер)
    float setpoint;       // Текущая целевая уставка тока (физические Амперы)
    float integrator;     // Накопленная интегральная составляющая выхода (Вольты)
    float out_min;        // Минимальный предел управления UCC3895 (0.0f Вольт)
    float out_max;        // Максимальный предел управления UCC3895 (обычно 3.3f Вольт)
} PI_Controller_t;

/* Экспорт структуры регулятора для возможности чтения параметров (например, для отладки) */
extern volatile PI_Controller_t pid;

/**
 * @brief Инициализация ПИ-регулятора тока (Скрывает объект внутри реализации)
 * @note  Внутри функции происходит автоматическое умножение дискретного шага Ki = ki_raw * 0.00005f
 * @param kp Пропорциональный коэффициент (В/А)
 * @param ki_raw Базовый интегральный коэффициент (1/с)
 * @param out_min Минимальное управляющее напряжение (Вольты)
 * @param out_max Максимальное управляющее напряжение (Вольты)
 */
void PI_Regulator_Init(float kp, float ki_raw, float out_min, float out_max);

/**
 * @brief Динамическое изменение целевой уставки тока (Вызывается из FSM_MMA_Process)
 * @param setpoint Новая уставка тока в физических Амперах
 */
void PI_Regulator_Set_Setpoint(float setpoint);

/**
 * @brief Сброс интегратора (Anti-Windup / Мгновенная очистка накопленной ошибки)
 * @note  Вызывается при глушении ШИМ и переключении критических состояний во избежание токового удара.
 */
void PI_Regulator_Reset(void);

/**
 * @brief Высокоскоростной расчет управляющего воздействия (Вызов каждые 50 мкс в TIM2)
 * @param current_feedback Физическое значение тока дуги в Амперах (уже пересчитанное из кодов АЦП)
 * @return float Управляющее напряжение для UCC3895 в диапазоне [out_min ... out_max] (Вольты)
 */
float PI_Regulator_Update(float current_feedback);

#endif // REGULATOR_H
