#ifndef SERVICES_INC_SIGNAL_PROCESSING_H_
#define SERVICES_INC_SIGNAL_PROCESSING_H_

#include <stdint.h>
#include "main.h"
#include "config.h" // ИСПРАВЛЕНИЕ: Подключаем для видимости ADC_BUFFER_SIZE и индексов каналов

/* ========================================================================== */
/*                      КОНСТАНТЫ И РАЗМЕРНОСТИ БУФЕРОВ                       */
/* ========================================================================== */

/* 
 * Физический буфер DMA увеличен в 2 раза для реализации Ping-Pong буферизации.
 * Рассчитывается предкомпилятором: (5 каналов * 16 выборок) * 2 = 160 элементов uint16_t.
 */
#define PING_PONG_BUFF_SIZE     (ADC_BUFFER_SIZE * 2U)

/* ========================================================================== */
/*                          СИСТЕМНЫЕ ПРОТОТИПЫ ФУНКЦИЙ                       */
/* ========================================================================== */

/**
 * @brief Глобальная инициализация АЦП-контура обработки сигналов инвертора.
 * @note Выполняет очистку внутренних ОЗУ-массивов фильтра EMA и осуществляет
 *       физический запуск ADC1 в связке с контроллером DMA2 в циклическом режиме.
 *       Вызывается один раз при старте системы в main.c.
 */
void Signal_Processing_Init(void);

/**
 * @brief Высокоскоростной пакетный обработчик оверсэмплинга и фильтрации.
 * @note Вызывается СТРОГО в прерываниях DMA (Half Transfer и Transfer Complete).
 *       Вычисляет среднее арифметическое окно, накладывает маску шумов ЭМП
 *       и обновляет значения цифровых фильтров Бесселя 1-го порядка (EMA).
 */
void Signal_Processing_Update(void);

/**
 * @brief Публикация отфильтрованных значений в публичный снапшот.
 * @note  Копирование одиночного float на Cortex-M4 атомарно на уровне транзакции шины;
 *        вызывается после Signal_Processing_Update() в DMA2_Stream0_IRQHandler.
 */
void Signal_Processing_Publish(void);

/**
 * @brief Безопасное чтение отфильтрованного значения произвольного канала в кодах АЦП (12-бит).
 * @param channel_idx Уникальный индекс измеряемого канала из Adc_Channel_Index_t (config.h)
 * @return float Сглаженное значение канала в сырых кодах АЦП (от 0.0f до 4095.0f)
 */
float Signal_Processing_Get_Filtered_Code(uint32_t channel_idx);

/* ========================================================================== */
/*           ИНТЕРФЕЙСНЫЕ ФУНКЦИИ ВЗАИМОДЕЙСТВИЯ С ПРЕРЫВАНИЕМ TIM2           */
/* ========================================================================== */

/**
 * @brief  Получить актуальный отфильтрованный код напряжения дуги для конечного автомата.
 * @note   Используется прерыванием TIM2_IRQHandler (20 кГц).
 * @retval Код АЦП напряжения (0...4095)
 */
uint16_t Signal_Processing_Get_Voltage(void);

/**
 * @brief  Получить актуальный отфильтрованный код тока дуги для конечного автомата.
 * @note   Используется прерыванием TIM2_IRQHandler (20 кГц).
 * @retval Код АЦП тока (0...4095)
 */
uint16_t Signal_Processing_Get_Current(void);

#endif /* SERVICES_INC_SIGNAL_PROCESSING_H_ */

