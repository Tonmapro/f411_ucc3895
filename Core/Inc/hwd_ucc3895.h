#ifndef APPLICATION_HWD_UCC3895_H
#define APPLICATION_HWD_UCC3895_H

#include <stdint.h>

/* Глобальный флаг критической аварии силовой части (latch): ставится в EXTI15_10_IRQHandler,
   сбрасывается только через UCC3895_Clear_Fault() после устранения причины */
extern volatile uint8_t global_fault_flag;

/**
 * @brief  Математические параметры ШИМ-интегратора (виртуального ЦАП)
 * @note   ARR = 3839 обеспечивает частоту ШИМ 25 кГц при тактировании таймера 96 МГц.
 *         Согласно Reference Manual, для получения честных 100% заполнения (чистые 3.3 В)
 *         коэффициент заполнения должен масштабироваться до значения (ARR + 1).
 */
#define UCC3895_ARR_MAX          3839U  // Значение, записываемое в регистр TIM4->ARR
#define UCC3895_PWM_PERIOD_TICKS (UCC3895_ARR_MAX + 1U) // Полный физический период (3840)

/**
 * @brief  Инициализация аппаратной периферии для управления UCC3895 (TIM4 + EXTI12)
 */
void UCC3895_Init(void);

/**
 * @brief  Аппаратное включение генерации ШИМ контроллера UCC3895 (SS/EN = HIGH)
 * @note   Атомарно защищено: функция проигнорирует вызов, если активен флаг аварии.
 */
void UCC3895_Enable(void);

/**
 * @brief  Мгновенный аппаратный останов UCC3895 (SS/EN = LOW)
 * @note   Запись в регистр BSRR выполняется за 1 такт процессора.
 */
void UCC3895_Disable(void);

/**
 * @brief  Установка управляющего напряжения на входе UCC3895 (через ШИМ + ФНЧ)
 * @param  volts: Требуемое аналоговое напряжение от 0.0f до 3.3f Вольт
 */
void UCC3895_Set_Control_Voltage(float volts);

/**
 * @brief  Проверка состояния флага критической аварии силовой части
 * @retval 1 — авария активна (инвертор заблокирован), 0 — система исправна
 */
uint8_t UCC3895_Is_Fault_Active(void);

/**
 * @brief  Сброс флага аварии после устранения перегрева или КЗ сети
 */
void UCC3895_Clear_Fault(void);

#endif // APPLICATION_HWD_UCC3895_H
