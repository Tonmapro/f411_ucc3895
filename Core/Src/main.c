/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  LL_APB2_GRP1_EnableClock(LL_APB2_GRP1_PERIPH_SYSCFG);
  LL_APB1_GRP1_EnableClock(LL_APB1_GRP1_PERIPH_PWR);

  /* System interrupt init*/
  NVIC_SetPriorityGrouping(NVIC_PRIORITYGROUP_4);

  /* SysTick_IRQn interrupt configuration */
  NVIC_SetPriority(SysTick_IRQn, NVIC_EncodePriority(NVIC_GetPriorityGrouping(),15, 0));

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_SPI1_Init();
  MX_TIM11_Init();
  /* USER CODE BEGIN 2 */
    
  // 2. Инициализация математического ядра (АЦП, Фильтры, Регулятор)
  Signal_Processing_Init(); // Инициализация ADC1 + DMA в режиме Circular
  PI_Regulator_Init(0.5f, 15.0f, 0.0f, 3.3f); // Кп, Ки, лимиты в Вольтах для UCC
  FSM_MMA_Init();

  // 3. Инициализация железа исполнительных механизмов
  UCC3895_Init();      // Конфигурация TIM4 ШИМ и защиты EXTI (теперь по спаду Falling)
  UCC3895_Clear_Fault();// Снимаем защёлку аварии ПОСЛЕ инициализации: на макетке без
                       // силовой части PB12 мог защёлкнуть FAULT при старте. Одноразовый
                       // сброс позволяет войти в STANDBY. При реальной аварии EXTI снова
                       // защёлкнет флаг, и UI покажет мигающий текст — это корректно.
  Encoder_Init();      // Аппаратный декодер энкодера TIM3 (PA6/PA7, кнопка PB7)
  Config_Load();       // Загрузка уставок из Flash: режим (MMA/Lift-TIG) + ток
  Encoder_Set_Value(Inverter.target_current); // Синхронизация фильтра энкодера с загруженным током
  UI_Manager_Init();   // Инициализация OLED и графических буферов (с двойной буферизацией)
  Cooling_Init();
    
  // 4. Настройка аппаратного приоритета прерывания таймера ПИ-регулятора/FSM (Частота 20 кГц)
  // Задаем приоритет 1 (чуть ниже, чем у защиты EXTI15_10, которая равна 0)
  NVIC_SetPriority(TIM2_IRQn, NVIC_EncodePriority(NVIC_GetPriorityGrouping(), 1, 0));
  NVIC_EnableIRQ(TIM2_IRQn);

  // Безопасный запуск силовой математики ПОСЛЕ инициализации всего железа
  LL_TIM_ClearFlag_UPDATE(TIM2); // Очищаем возможный ложный флаг
  LL_TIM_EnableIT_UPDATE(TIM2);
  LL_TIM_EnableCounter(TIM2);

  // ВНИМАНИЕ (п.5): UCC3895_Enable() здесь НЕ вызывается.
  // Мост включается автоматом FSM в состоянии STANDBY (режим ОCV с дежурным
  // током 10 А) — на первом же тике TIM2 (50 мкс). Аппаратный soft-start
  // UCC3895 (SS-конденсатор) обеспечивает плавный разгон силовой части.
  
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
 
  while (1)
  {
    /* 1. Высокоскоростной асинхронный опрос энкодера (чистый LL) */
    // Считывает тики TIM5, фильтрует помехи дуги и обновляет атомарную переменную тока
    Encoder_Update_Value();

    /* 2. Менеджер UI: проверка Encoder_Is_Pressed, отрисовка меню в теневой буфер, Swap буферов */
    UI_Manager_Update();
        
    //1.Читает уже отфильтрованные в прерывании коды АЦП (Signal_Processing_Get_Filtered_Code)
    // без шумов дуги.
    //2.Рассчитывает гистерезис включения/выключения
    //3.Крутит линейную интерполяцию ШИМ таймера TIM11
     Cooling_Process();

    /* 4. Отложенное сохранение настроек во Flash: через 3 с после последнего
       изменения уставки/режима (запись выполняется только на холостом ходу) */
     Config_Check_Timeout();
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

/**
  * @brief System Clock Configuration
  * @retval None
  */
void SystemClock_Config(void)
{
  LL_FLASH_SetLatency(LL_FLASH_LATENCY_3);
  while(LL_FLASH_GetLatency()!= LL_FLASH_LATENCY_3)
  {
  }
  LL_PWR_SetRegulVoltageScaling(LL_PWR_REGU_VOLTAGE_SCALE1);
  LL_RCC_HSE_Enable();

   /* Wait till HSE is ready */
  while(LL_RCC_HSE_IsReady() != 1)
  {

  }
  LL_RCC_PLL_ConfigDomain_SYS(LL_RCC_PLLSOURCE_HSE, LL_RCC_PLLM_DIV_25, 192, LL_RCC_PLLP_DIV_2);
  LL_RCC_PLL_Enable();

   /* Wait till PLL is ready */
  while(LL_RCC_PLL_IsReady() != 1)
  {

  }
  while (LL_PWR_IsActiveFlag_VOS() == 0)
  {
  }
  LL_RCC_SetAHBPrescaler(LL_RCC_SYSCLK_DIV_1);
  LL_RCC_SetAPB1Prescaler(LL_RCC_APB1_DIV_2);
  LL_RCC_SetAPB2Prescaler(LL_RCC_APB2_DIV_1);
  LL_RCC_SetSysClkSource(LL_RCC_SYS_CLKSOURCE_PLL);

   /* Wait till System clock is ready */
  while(LL_RCC_GetSysClkSource() != LL_RCC_SYS_CLKSOURCE_STATUS_PLL)
  {

  }
  LL_Init1msTick(96000000);
  /* LL_InitTick() в этой версии драйвера НЕ ставит бит TICKINT — прерывание SysTick
     не генерируется, SysTick_Handler не вызывается, и системный счётчик времени
     s_system_ms_ticks всегда 0. Это ломает: счёт времени, мигание UI, и отложенное
     сохранение уставок во Flash (Config_Check_Timeout).
     Включаем прерывание вручную: */
  SysTick->CTRL |= SysTick_CTRL_TICKINT_Msk;
  LL_SetSystemCoreClock(96000000);
  LL_RCC_SetTIMPrescaler(LL_RCC_TIM_PRESCALER_TWICE);
}

