static void SSD1306_WriteCommand(uint8_t cmd) {
    HAL_GPIO_WritePin(OLED_DC_GPIO_Port, OLED_DC_Pin, GPIO_PIN_RESET); // DC = 0
    HAL_SPI_Transmit(&hspi1, &cmd, 1, 10);
}

void SSD1306_Init(void) {
    HAL_GPIO_WritePin(OLED_RES_GPIO_Port, OLED_RES_Pin, GPIO_PIN_RESET);
    HAL_Delay(10);
    HAL_GPIO_WritePin(OLED_RES_GPIO_Port, OLED_RES_Pin, GPIO_PIN_SET);
    HAL_Delay(10);

    SSD1306_WriteCommand(0xAE); SSD1306_WriteCommand(0x20); SSD1306_WriteCommand(0x00);
    SSD1306_WriteCommand(0xB0); SSD1306_WriteCommand(0xC8); SSD1306_WriteCommand(0x00);
    SSD1306_WriteCommand(0x10); SSD1306_WriteCommand(0x40); SSD1306_WriteCommand(0x81);
    SSD1306_WriteCommand(0xFF); // Яркость на максимум для улицы
    SSD1306_WriteCommand(0xA1); SSD1306_WriteCommand(0xA6); SSD1306_WriteCommand(0xA8);
    SSD1306_WriteCommand(0x3F); SSD1306_WriteCommand(0xA4); SSD1306_WriteCommand(0xD3);
    SSD1306_WriteCommand(0x00); SSD1306_WriteCommand(0xD5); SSD1306_WriteCommand(0x80);
    SSD1306_WriteCommand(0xD9); SSD1306_WriteCommand(0xF1); SSD1306_WriteCommand(0xDA);
    SSD1306_WriteCommand(0x12); SSD1306_WriteCommand(0xDB); SSD1306_WriteCommand(0x40);
    SSD1306_WriteCommand(0x8D); SSD1306_WriteCommand(0x14); SSD1306_WriteCommand(0xAF);
    SSD1306_Clear();
}

void SSD1306_Clear(void) { memset(SSD1306_Buffer, 0, 1024); }

void SSD1306_DrawPixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
    if (color) SSD1306_Buffer[x + (y / 8) * 128] |= (1 << (y % 8));
    else       SSD1306_Buffer[x + (y / 8) * 128] &= ~(1 << (y % 8));
}

void SSD1306_DrawLine(int x1, int y1, int x2, int y2, uint8_t color) {
    (void)y2; // Предупреждение исчезнет
    for (int x = x1; x <= x2; x++) SSD1306_DrawPixel(x, y1, color); // Базовая горизонтальная линия
}

void SSD1306_DrawBigChar(int x, int y, char c) {
    uint8_t font_idx = 16; // Пробел
    if (c >= '0' && c <= '9') font_idx = c - '0';
    else if (c == 'A' || c == 'a') font_idx = 10;
     else if (c == 'L' || c == 'l') {
        font_idx = 11;
    } 
    else if (c == 'R' || c == 'r') {
        font_idx = 12; // Индекс 12 больше не превратится в 11!
    } 
    else if (c == 'M' || c == 'm') {
        font_idx = 13;
    } 
    else if (c == '!') {
        font_idx = 14;
    } 
    else if (c == '-') {
        font_idx = 15;
    }

    for (int row = 0; row < 32; row++) {
        uint16_t line_bits = (Font_16x32[font_idx][row * 2] << 8) | Font_16x32[font_idx][row * 2 + 1];
        for (int col = 0; col < 16; col++) {
            if (line_bits & (0x8000 >> col)) SSD1306_DrawPixel(x + col, y + row, 1);
            else                             SSD1306_DrawPixel(x + col, y + row, 0);
        }
    }
}

void SSD1306_DrawBigString(int x, int y, char* str) {
    while (*str) { SSD1306_DrawBigChar(x, y, *str); x += 18; str++; }
}

void SSD1306_Render_DMA(void) {
    if (dma_busy) return;
    SSD1306_WriteCommand(0x21); SSD1306_WriteCommand(0);    SSD1306_WriteCommand(127);
    SSD1306_WriteCommand(0x22); SSD1306_WriteCommand(0);    SSD1306_WriteCommand(7);
    HAL_GPIO_WritePin(OLED_DC_GPIO_Port, OLED_DC_Pin, GPIO_PIN_SET); // DC = 1 (Данные)
    dma_busy = 1;
    HAL_SPI_Transmit_DMA(&hspi1, SSD1306_Buffer, 1024);
}

void HAL_SPI_TxCpltCallback(SPI_HandleTypeDef *hspi) { if (hspi->Instance == SPI1) dma_busy = 0; }
uint8_t SSD1306_Is_Busy(void) { return dma_busy; }

// Вывод одного символа стандартного шрифта (8х16)
void SSD1306_DrawChar(int x, int y, char c, uint8_t color) {
    if (c < 32 || c > 126) return; // Обрабатываем только печатные ASCII символы
    uint8_t font_idx = c - 32;     // Смещение относительно пробела

    for (int row = 0; row < 16; row++) {
        // Предполагается, что каждый ряд символа занимает 1 байт (8 бит)
        uint8_t line_bits = Font_8x16[font_idx][row]; 
        for (int col = 0; col < 8; col++) {
            if (line_bits & (0x80 >> col)) {
                SSD1306_DrawPixel(x + col, y + row, color);
            } else {
                SSD1306_DrawPixel(x + col, y + row, !color); // Очистка фона вокруг буквы
            }
        }
    }
}

// Вывод всей строки стандартного шрифта
void SSD1306_DrawString(int x, int y, char* str, uint8_t color) {
    while (*str) {
        SSD1306_DrawChar(x, y, *str, color);
        x += 8; // Сдвиг на 8 пикселей вправо для следующего символа 8x16
        str++;
    }
}

void UI_Process_And_Draw(void) {
    char cur_buff[8];   
    char volt_buff[8];  
    char meas_buff[8]; // Буфер для реального измеряемого напряжения
    
    SSD1306_Clear();

    // =================================================================
    // ВЕРХНЯЯ ЗОНА: Вывод крупного Тока ИЛИ Кодов Аварии
    // =================================================================
    if (Welder.state == STATE_ALARM) {
        if ((HAL_GetTick() / 400) % 2) {
            if (WelderAlarms.hardware_break)      SSD1306_DrawBigString(16, 2, "SHORT!"); 
            else if (WelderAlarms.low_15v)        SSD1306_DrawBigString(10, 2, "220V-!"); 
            else if (WelderAlarms.ntc_radiator)   SSD1306_DrawBigString(28, 2, "HOT!!"); 
            else if (WelderAlarms.fan_failed)     SSD1306_DrawBigString(20, 2, "FAN ER");
        }
    } 
    else {
        // Если все в норме - выводим крупные цифры тока сверху
        int current_int = (int)Welder.current_setpoint;
        cur_buff[0] = (current_int / 100) + '0';          
        cur_buff[1] = ((current_int % 100) / 10) + '0';   
        cur_buff[2] = (current_int % 10) + '0';           
        cur_buff[3] = 'A';
        cur_buff[4] = '\0';

        if (cur_buff[0] == '0') {
            SSD1306_DrawBigString(38, 2, &cur_buff[1]); 
        } else {
            SSD1306_DrawBigString(28, 2, cur_buff);
        }
    }

    // Разделительная линия
    SSD1306_DrawLine(0, 37, 128, 37, WHITE);

    // =================================================================
    // НИЖНЯЯ ЗОНА: Новая сбалансированная компоновка (Мелкий шрифт 8x16)
    // =================================================================
    
    // 1. ЛЕВАЯ ЧАСТЬ (X = 4): Вывод настраиваемой уставки
    if (current_selected_mode == 1) {
        // В режиме TIG уставка всегда только одна - Ток (дублируем мелким шрифтом вниз)
        int cur_set = (int)Welder.current_setpoint;
        cur_buff[0] = (cur_set / 100) + '0';
        cur_buff[1] = ((cur_set % 100) / 10) + '0';
        cur_buff[2] = (cur_set % 10) + '0';
        cur_buff[3] = 'A';
        cur_buff[4] = '\0';
        
        // Убираем лидирующий ноль для мелкого шрифта
        if (cur_buff[0] == '0') SSD1306_DrawString(4, 44, &cur_buff[1], WHITE);
        else                    SSD1306_DrawString(4, 44, cur_buff, WHITE);
    } 
    else {
        // В режиме MMA смотрим, что сейчас крутит пользователь
        if (ui_edit_target == 0) {
            // Если крутим ТОК, выводим его мелкую копию вниз
            int cur_set = (int)Welder.current_setpoint;
            cur_buff[0] = (cur_set / 100) + '0';
            cur_buff[1] = ((cur_set % 100) / 10) + '0';
            cur_buff[2] = (cur_set % 10) + '0';
            cur_buff[3] = 'A';
            cur_buff[4] = '\0';
            
            if (cur_buff[0] == '0') SSD1306_DrawString(4, 44, &cur_buff[1], WHITE);
            else                    SSD1306_DrawString(4, 44, cur_buff, WHITE);
        } else {
            // Если переключились кликом на ВОЛЬТЫ, выводим уставку ограничения вольт ХХ
            int v_set_int = (int)(Welder.voltage_setpoint * 10.0f);
            volt_buff[0] = (v_set_int / 100) + '0';        
            volt_buff[1] = ((v_set_int % 100) / 10) + '0'; 
            volt_buff[2] = '.';                           
            volt_buff[3] = (v_set_int % 10) + '0';         
            volt_buff[4] = 'V';
            volt_buff[5] = '\0';
            
            SSD1306_DrawString(4, 44, volt_buff, WHITE);
        }
    }

    // 2. ЦЕНТРАЛЬНАЯ ЧАСТЬ (X = 52): Всегда реальное измеряемое напряжение дуги
    int volt_meas = (int)(Welder.voltage_filtered * 10.0f);
    if (volt_meas > 999) volt_meas = 999;
    
    meas_buff[0] = (volt_meas / 100) + '0';        
    meas_buff[1] = ((volt_meas % 100) / 10) + '0'; 
    meas_buff[2] = '.';                           
    meas_buff[3] = (volt_meas % 10) + '0';         
    meas_buff[4] = 'V';
    meas_buff[5] = '\0';
    
    SSD1306_DrawString(52, 44, meas_buff, WHITE); // Вывод строго по центру нижней строки

    // 3. ПРАВАЯ ЧАСТЬ (X = 96): Маркер режима
    if (current_selected_mode == 0) SSD1306_DrawString(96, 44, "MMA", WHITE);
    else                            SSD1306_DrawString(96, 44, "TIG", WHITE);
}

