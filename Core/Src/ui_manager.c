/**
 * @brief Попиксельная отрисовка строго в текущий скрытый буфер (Back Buffer)
 */
static void UI_DrawPixel_BackBuf(int x, int y, uint8_t color) {
    if (x < 0 || x >= (int)SSD1306_WIDTH || y < 0 || y >= (int)SSD1306_HEIGHT) return;
    
    // Получаем адрес буфера, в котором сейчас идет рендеринг в ОЗУ
    uint8_t *back_buf = OLED_Get_BackBuffer_Ptr();
    if (back_buf == NULL) return;

    if (color) {
        back_buf[x + (y / 8) * SSD1306_WIDTH] |= (1 << (y % 8));
    } else {
        back_buf[x + (y / 8) * SSD1306_WIDTH] &= ~(1 << (y % 8));
    }
}

/**
 * @brief Высокоскоростная отрисовка горизонтальной разделительной линии
 */
static void UI_DrawHorizontalLine(int x1, int x2, int y, uint8_t color) {
    if (x1 < 0) x1 = 0;
    if (x2 >= (int)SSD1306_WIDTH) x2 = (int)SSD1306_WIDTH - 1;
    
    for (int x = x1; x <= x2; x++) {
        UI_DrawPixel_BackBuf(x, y, color);
    }
}

/**
 * @brief Отрисовка символа стандартного шрифта 8х16
 */
static void UI_DrawChar_8x16(int x, int y, char c, uint8_t color) {
    if (c < 32 || c > 126) return; 
    uint8_t font_idx = c - 32; // Смещение относительно пробела в ASCII

    for (int row = 0; row < 16; row++) {
        uint8_t line_bits = Font_8x16[font_idx][row]; 
        for (int col = 0; col < 8; col++) {
            if (line_bits & (0x80 >> col)) {
                UI_DrawPixel_BackBuf(x + col, y + row, color);
            } else {
                UI_DrawPixel_BackBuf(x + col, y + row, !color); // Очистка фона (инверсия)
            }
        }
    }
}

