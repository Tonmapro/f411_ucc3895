void UI_Manager_Init(void) {
    OLED_Init(); // Инициализация двубуферного драйвера дисплея
}

void UI_Manager_Update(void) {
    ms_counter = System_Get_Tick(); // Получаем системное время (SysTick, 1 мс)
    ui_frame_counter++;             // Кадровый счётчик (растёт всегда)

    /* 1. ЗАЩИТА ШИНЫ: Если DMA сейчас занят выталкиванием старого кадра, выходим */
    if (OLED_GetStatus() == OLED_BUSY_DMA) {
        return;
    }

    /* 2. ОЧИСТКА: Обнуляем теневой (Back) буфер ОЗУ через memset за 1 такт */
    OLED_Clear(OLED_COLOR_BLACK);

    /* 3. АТОМАРНЫЙ СНИМОК: Копируем данные из быстрого прерывания FSM (20 кГц) */
    ui_data_snap.target_current = Inverter.target_current;
    ui_data_snap.actual_voltage = Inverter.actual_voltage;
    ui_data_snap.state          = Inverter.state;
    ui_data_snap.fault_code     = Inverter.fault_code;

    /* ========================================================================== */
    /* ЗОНА 1 (Верхняя, Y = 2): Крупный Ток уставки или Мигающий Экран Аварии     */
    /* ========================================================================== */
    if (ui_data_snap.state == SYS_STATE_FAULT) {
        /* Мигание ошибки: каждый чётный 50-кадровый интервал текст виден,
           нечётный — скрыт. Надёжно работает независимо от SysTick. */
        if ((ui_frame_counter & 0x20U) == 0U) {
            switch (ui_data_snap.fault_code) {
                case FAULT_CODE_OVERCURRENT:  UI_PrintBigStr(2, "SHORT!");  break;
                case FAULT_CODE_LOW_15V:      UI_PrintBigStr(2, "220V-!");  break;
                case FAULT_CODE_OVERHEAT_IGBT:
                case FAULT_CODE_OVERHEAT_DIO: UI_PrintBigStr(2, "HOT!!");  break;
                case FAULT_CODE_FAN_BLOCKED:  UI_PrintBigStr(2, "FAN ER");  break;
                case FAULT_CODE_SENSOR_OPEN:  UI_PrintBigStr(2, "TSENSOR"); break;
                default:                      UI_PrintBigStr(2, "ERROR");  break;
            }
        }
    } else {
        UI_PrintCurrent((int)ui_data_snap.target_current);
    }

    /* РАЗДЕЛИТЕЛЬНАЯ ГЕОМЕТРИЧЕСКАЯ ЛИНИЯ */
    UI_DrawHorizontalLine(0, 127, 37, 1);

    /* ========================================================================== */
    /* ЗОНА 2 (Нижняя, Y = 40): Информационный бар мелким шрифтом 8x16            */
    /* ========================================================================== */
    char bar_buff[8];

    // --- ПОДЗОНА 2.1: Левый угол (X = 4) -> Настраиваемая уставка тока или вольт ХХ ---
    if (current_selected_mode == 1) {
        int cur_set = (int)ui_data_snap.target_current;
        bar_buff[0] = (cur_set / 100) + '0';
        bar_buff[1] = ((cur_set % 100) / 10) + '0';
        bar_buff[2] = (cur_set % 10) + '0';
        bar_buff[3] = 'A';
        bar_buff[4] = '\0';

        if (bar_buff[0] == '0') UI_PrintStr_8x16(4, 40, &bar_buff[1], 1);
        else UI_PrintStr_8x16(4, 40, bar_buff, 1);
    } else {
        if (ui_edit_target == 0) {
            int cur_set = (int)ui_data_snap.target_current;
            bar_buff[0] = (cur_set / 100) + '0';
            bar_buff[1] = ((cur_set % 100) / 10) + '0';
            bar_buff[2] = (cur_set % 10) + '0';
            bar_buff[3] = 'A';
            bar_buff[4] = '\0';

            if (bar_buff[0] == '0') UI_PrintStr_8x16(4, 40, &bar_buff[1], 1);
            else UI_PrintStr_8x16(4, 40, bar_buff, 1);
        } else {
            bar_buff[0] = '7';
            bar_buff[1] = '5';
            bar_buff[2] = '.';
            bar_buff[3] = '0';
            bar_buff[4] = 'V';
            bar_buff[5] = '\0';

            UI_PrintStr_8x16(4, 40, bar_buff, 1);
        }
    }

    // --- ПОДЗОНА 2.2: Центр (X = 52) -> Реальное измеряемое напряжение дуги из АЦП ---
    uint32_t volt_meas = (((uint32_t)ui_data_snap.actual_voltage * 1000U) + 2048U) / 4096U;
    if (volt_meas > 999U) volt_meas = 999U;

    char meas_buff[8];
    meas_buff[0] = (volt_meas / 100) + '0';
    meas_buff[1] = ((volt_meas % 100) / 10) + '0';
    meas_buff[2] = '.';
    meas_buff[3] = (volt_meas % 10) + '0';
    meas_buff[4] = 'V';
    meas_buff[5] = '\0';

    UI_PrintStr_8x16(52, 40, meas_buff, 1);

    // --- ПОДЗОНА 2.3: Правый угол (X = 96) -> Маркер выбранного режима MMA/TIG ---
    if (current_selected_mode == 0) {
        UI_PrintStr_8x16(96, 40, "MMA", 1);
    } else {
        UI_PrintStr_8x16(96, 40, "TIG", 1);
    }

    // --- ДИАГНОСТИКА (V14): 7 чередующихся фаз (~0.35 с каждая, кадровый счётчик) ---
    // Ф0: V14 xx:x  — версия прошивки + состояние + fault_code
    // Ф1: Dnnn     — цифровой уровень падов PA2/PA3/PA5 из IDR (неинформативен в ANALOG)
    // Ф2: Annnn    — код канала PA3 (NTC IGBT)
    // Ф3: Bnnnn    — код канала PA5 (NTC диодов)
    // Ф4: Fnnnn    — код тока кулера PB0: <40 обрыв (продувка!), >3500 клин
    // Ф5: Ennnn    — код канала +15В (PA2): <700 → «220V-!»
    // Ф6: Mnnnnn   — миллисекунды SysTick: счёт ДОЛЖЕН расти.
    char st_dbg[10];
    const char *hex_tbl = "0123456789ABCDEF";
    switch ((ui_frame_counter >> 8) % 7U) {
    case 0:
        st_dbg[0] = 'V';
        st_dbg[1] = hex_tbl[(FW_BUILD / 10U) % 10U];   /* десятки версии (V10, V11) */
        st_dbg[2] = hex_tbl[FW_BUILD % 10U];           /* единицы версии */
        st_dbg[3] = ' ';
        st_dbg[4] = hex_tbl[(ui_data_snap.state >> 4) & 0xF];
        st_dbg[5] = hex_tbl[ui_data_snap.state & 0xF];
        st_dbg[6] = ':';
        st_dbg[7] = hex_tbl[ui_data_snap.fault_code & 0xF];
        st_dbg[8] = '\0';
        break;
    case 1: {
        uint32_t idr = GPIOA->IDR;
        st_dbg[0] = 'D';
        st_dbg[1] = (char)('0' + ((idr >> 2) & 1U)); /* PA2: +15В (ANALOG, без подтяжки) */
        st_dbg[2] = (char)('0' + ((idr >> 3) & 1U)); /* PA3: NTC IGBT  (ANALOG, без подтяжки)  */
        st_dbg[3] = (char)('0' + ((idr >> 5) & 1U)); /* PA5: NTC диоды (ANALOG, без подтяжки)  */
        st_dbg[4] = '\0';
        break;
    }
    case 2: {
        uint16_t a_cur = (uint16_t)(Signal_Processing_Get_Filtered_Code(ADC_TEMP_IDX) + 0.5f);
        if (a_cur > 9999U) a_cur = 9999U;
        st_dbg[0] = 'A';
        st_dbg[1] = (char)('0' + (a_cur / 1000U) % 10U);
        st_dbg[2] = (char)('0' + (a_cur / 100U) % 10U);
        st_dbg[3] = (char)('0' + (a_cur / 10U) % 10U);
        st_dbg[4] = (char)('0' + a_cur % 10U);
        st_dbg[5] = '\0';
        break;
    }
    case 3: {
        uint16_t b_cur = (uint16_t)(Signal_Processing_Get_Filtered_Code(ADC_TEMP_DIO_IDX) + 0.5f);
        if (b_cur > 9999U) b_cur = 9999U;
        st_dbg[0] = 'B';
        st_dbg[1] = (char)('0' + (b_cur / 1000U) % 10U);
        st_dbg[2] = (char)('0' + (b_cur / 100U) % 10U);
        st_dbg[3] = (char)('0' + (b_cur / 10U) % 10U);
        st_dbg[4] = (char)('0' + b_cur % 10U);
        st_dbg[5] = '\0';
        break;
    }
    case 4: {
        uint16_t f_cur = (uint16_t)(Signal_Processing_Get_Filtered_Code(ADC_FAN_CURR_IDX) + 0.5f);
        if (f_cur > 9999U) f_cur = 9999U;
        st_dbg[0] = 'F';
        st_dbg[1] = (char)('0' + (f_cur / 1000U) % 10U);
        st_dbg[2] = (char)('0' + (f_cur / 100U) % 10U);
        st_dbg[3] = (char)('0' + (f_cur / 10U) % 10U);
        st_dbg[4] = (char)('0' + f_cur % 10U);
        st_dbg[5] = '\0';
        break;
    }
    case 5: {
        uint16_t e_cur = (uint16_t)(Signal_Processing_Get_Filtered_Code(ADC_V15V_IDX) + 0.5f);
        if (e_cur > 9999U) e_cur = 9999U;
        st_dbg[0] = 'E';
        st_dbg[1] = (char)('0' + (e_cur / 1000U) % 10U);
        st_dbg[2] = (char)('0' + (e_cur / 100U) % 10U);
        st_dbg[3] = (char)('0' + (e_cur / 10U) % 10U);
        st_dbg[4] = (char)('0' + e_cur % 10U);
        st_dbg[5] = '\0';
        break;
    }
    default: {
        uint32_t ms = System_Get_Tick() % 100000U;
        st_dbg[0] = 'M';
        st_dbg[1] = (char)('0' + (ms / 10000U) % 10U);
        st_dbg[2] = (char)('0' + (ms / 1000U) % 10U);
        st_dbg[3] = (char)('0' + (ms / 100U) % 10U);
        st_dbg[4] = (char)('0' + (ms / 10U) % 10U);
        st_dbg[5] = (char)('0' + ms % 10U);
        st_dbg[6] = '\0';
        break;
    }
    }
    UI_PrintDiag(0, st_dbg);

    // 4. Асинхронный флип (подмена указателей), кадр мгновенно улетает по DMA
    OLED_Swap_Buffers();
}
